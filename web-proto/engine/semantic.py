CATEGORY_NAMES: Tuple[str, ...] = tuple(CATEGORY_LEXICON.keys())


def category_members(category: str) -> Tuple[str, ...]:
    """取类别词表（未知类别直接报错，不静默返回空——空词表会让该动作恒为「否」）。"""
    if category not in CATEGORY_LEXICON:
        raise KeyError(f"未知语义类别: {category}")
    return CATEGORY_LEXICON[category]


def category_answer(solution: str, category: str) -> str:
    """从汤底文本派生类别答案（是 / 否）。

    判定与 golden_qa 完全无关——这是刻意设计，见模块文档「答案怎么来」。
    """
    sol = solution or ""
    for w in category_members(category):
        if w in sol:
            return "是"
    return "否"


def matched_members(solution: str, category: str) -> List[str]:
    """返回汤底中命中该类别的词（诊断用：看词表到底靠哪些词命中）。"""
    sol = solution or ""
    return [w for w in category_members(category) if w in sol]


def build_category_bank() -> Tuple[List[str], Dict[str, List[str]]]:
    """语义动作库 = 类别名列表（题目无关，可跨题共享）。

    返回 (动作列表, 类别→词表)。刻意不做「按题库筛掉无用类别」——筛选会
    用到了题库答案信息，等于按答案裁剪动作空间。
    """
    return list(CATEGORY_NAMES), {k: list(v) for k, v in CATEGORY_LEXICON.items()}


class CategoryHost(Host):
    """按语义类别回答的主持人：答案从汤底文本派生。

    与 MockHost 的区别：MockHost 按 golden_qa 的 contains 做子串匹配
    （关键词动作用），本类按类别词表匹配汤底（语义类别动作用）。
    """

    def __init__(self, id: str = "category-host"):
        super().__init__(id=id, model="lexicon-match")

    def answer(self, puzzle: Puzzle, question: str, transcript: List[dict]) -> str:
        cat = _parse_category(question)
        if cat is None:
            return "无关"
        return category_answer(puzzle.solution, cat)


def _parse_category(question: str) -> "str | None":
    """从问句里取回类别名（渲染格式见 players/rl.py 的 render_question）。"""
    if "「" in question and "」" in question:
        cat = question.split("「", 1)[1].split("」", 1)[0]
        return cat if cat in CATEGORY_LEXICON else None
    return None


def coverage_report(puzzles: Sequence[Puzzle]) -> List[dict]:
    """每题的类别覆盖诊断：多少个类别答「是」，靠哪些词命中。

    用于前置验证——若某题一个类别都不命中，该题上语义动作拿不到任何
    信号（等价于关键词动作时代的「题003 零有效动作」漏洞）。
    """
    out = []
    for p in puzzles:
        hits = [c for c in CATEGORY_NAMES if category_answer(p.solution, c) == "是"]
        out.append({
            "soup_id": p.soup_id,
            "n_yes": len(hits),
            "yes_categories": hits,
            "matched": {c: matched_members(p.solution, c) for c in hits},
        })
    return out
