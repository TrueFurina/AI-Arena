"""L2 语义化动作空间：把「提问哪个关键词」升级为「提问哪个语义类别」。

────────────────────────────────────────────────────────────────────────────────
为什么必须有这个模块（上一轮结论直接指向这里）
────────────────────────────────────────────────────────────────────────────────
  关键词动作库（92 个动作）在 held-out 评测上真泛化增益**精确为 0**：
  动作是题目绑定的关键词，新题的关键词必然不同，没有任何迁移路径。
  样本阶梯 3→6→9 增益不改善，证明这是**动作抽象**的问题，不是数据量问题。

  语义类别动作把动作空间从「题目特有词」换成「跨题通用探针」：
    关键词动作 —— 「这件事和『海难』有关吗？」  只有题001 能答「是」
    语义类别动作 —— 「这件事和『交通工具』有关吗？」 任何题都能答
  动作变成**题目无关**后，状态也可以不含题目 ID（否则又是按题记忆），
  Q 值在题目间共享 → 迁移路径存在。

────────────────────────────────────────────────────────────────────────────────
答案怎么来（这是本模块最要紧的设计，防循环论证）
────────────────────────────────────────────────────────────────────────────────
  类别答案**从汤底文本机械派生**：类别 C 的词表里任意一个词作为子串出现在
  solution 中 → 回答「是」，否则「否」。

  理由与边界：
  · 主持人（Host）本来就知道汤底，用汤底判「是/否」在物理上是合法的，
    不是答案泄漏——泄漏指的是**提问者**看到汤底，这里提问者看不到。
  · 刻意**不**从 golden_qa 派生：golden_qa 的 answer 字段是我标注的，
    若用它决定类别答案，就等于把我的人工判断包装成客观信号，属循环论证。
    从 solution 派生则与 golden_qa 完全解耦（可断言二者独立）。
  · ⚠️ 残留的设计者知识（诚实披露）：**类别词表本身是我编写的**。词表是
    通用词汇（属词典性质，不是某题的答案），但仍可能包含了题库用词。
    因此 held-out 增益要扣除「词表覆盖」带来的部分——见 eval 脚本里的
    「随机不重复」基线对照，它把「仅靠不重复就能拿到的分」扣掉，剩下的
    才是真正学到的跨题先验。

────────────────────────────────────────────────────────────────────────────────
代价（必须一并陈述，勿只报好处）
────────────────────────────────────────────────────────────────────────────────
  语义类别换来迁移能力，但**牺牲了文本还原**：终局还原句由类别名拼成
  （「真相与以下要素有关：交通工具，死亡伤害。」），与汤底字符几乎不重合，
  F1 会很低。这不是 bug——类别动作本来就不携带还原所需的实体词。
  打通它需要一个「解码器」：RL 负责选探针、LLM 负责把确认的类别写成
  还原文本（L1×L2 结合），那是后续工作。
  因此语义模式下 **F1 与关键词模式不可比**，主指标是 dhit（去重线索命中率）。

────────────────────────────────────────────────────────────────────────────────
实测结果（2026-10-13，held-out 协议，题库 12 题 / 12 个语义类别 / 8 轮）
────────────────────────────────────────────────────────────────────────────────
  好坏各半，两条都报：

  好消息——迁移路径确实打开了：
    新题 dhit        语义 0.42~0.56  vs  关键词(题目条件) 0.00~0.17
    跨 5 个种子（n_train=6）差值 +0.271 ~ +0.479，全部为正
    且语义模式的「训练题 vs 新题」落差只有 +0.06 ~ −0.19，
    而关键词模式是 +0.44~+0.57（典型记忆）→ 语义模式没有靠记忆拿分

  坏消息——迁移过来的信息量很小，而且不随训练题增多而增长：
    真泛化增益（扣除随机不重复基线）+0.043 / +0.129 / +0.054（训练题 3/6/9）
    n_train=3 与 9 时跨种子**不稳健**（出现负值），只有 n_train=6 时 5/5 为正
    训练出的提问顺序与「直接按全局频率问」的参考值相差 ≤ 0.104
      → 学到的**只是全局先验**（哪些类别通常更有用），没有按题判断的能力
    oracle（已知新题答案再排顺序）dhit 0.58~0.75，明显更高，但那部分信息
      是题目特有的、题目无关的策略原则上拿不到

  结论：语义化动作把泛化增益从「精确 0」变成了「小且不稳定」，方向对了，
  但**还撑不起「具备泛化能力」的说法**。要让策略能按题调整又不靠记忆，
  下一步得把状态从「已问集合」升级为「汤面的语义特征」——特征既随题变化
  （可按题调整），又不暴露题目身份（不能靠记忆）。
"""
